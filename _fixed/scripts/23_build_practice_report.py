def set_run(run, size=14, bold=False, italic=False):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn('w:rFonts'))
    if rfonts is None:
        rfonts = OxmlElement('w:rFonts')
        rpr.append(rfonts)
    for a in ('w:ascii', 'w:hAnsi', 'w:cs', 'w:eastAsia'):
        rfonts.set(qn(a), FONT)


def para(doc, text="", align=WD_ALIGN_PARAGRAPH.JUSTIFY, size=14, bold=False,
         first_indent=True, space_after=6, line=1.5, left=None):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    if first_indent and text:
        pf.first_line_indent = Cm(1.25)
    if left is not None:
        pf.left_indent = Cm(left)
    pf.line_spacing = line
    pf.space_after = Pt(space_after)
    if text:
        set_run(p.add_run(text), size=size, bold=bold)
    return p


def heading(doc, text, level=1):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if level == 1 else WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(6)
    p.style = doc.styles["Heading 1"] if level == 1 else doc.styles["Heading 2"]
    for r in p.runs:
        set_run(r, size=16 if level == 1 else 14, bold=True)
    set_run(p.add_run(text), size=16 if level == 1 else 14, bold=True)
    return p


def add_image(doc, path, caption, width=5.9):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(2)
    run = p.add_run()
    run.add_picture(path, width=Inches(width))
    c = doc.add_paragraph()
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraph_format.space_after = Pt(8)
    set_run(c.add_run(caption), size=12, italic=True)


def table(doc, header, rows, caption=None):
    if caption:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(8)
        set_run(p.add_run(caption), size=13, bold=True)
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for j, h in enumerate(header):
        hdr[j].text = ""
        set_run(hdr[j].paragraphs[0].add_run(h), size=12, bold=True)
        hdr[j].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    for row in rows:
        cells = t.add_row().cells
        for j, val in enumerate(row):
            cells[j].text = ""
            set_run(cells[j].paragraphs[0].add_run(str(val)), size=12)
            cells[j].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    return t


def bullet(doc, text):
    p = para(doc, text, first_indent=True, left=1.0)
    p.paragraph_format.left_indent = Cm(1.0)


