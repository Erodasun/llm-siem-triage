# Формирует пояснительную записку для научного руководителя (docx).
# Простыми словами: что сделано, как устроено, как подключались к сервисам, что показать.
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from docx import Document
from docx.shared import Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH

from src.config import REPORTS

OUT = str(REPORTS / "Пояснение_для_научрука.docx")

doc = Document()
style = doc.styles["Normal"]
style.font.name = "Times New Roman"
style.font.size = Pt(12)


def h(text, level=1):
    doc.add_heading(text, level=level)


def p(text, bold=False):
    par = doc.add_paragraph()
    run = par.add_run(text)
    run.bold = bold
    return par


def b(text):
    doc.add_paragraph(text, style="List Bullet")


def table(headers, rows):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    for i, hh in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ""
        c.paragraphs[0].add_run(hh).bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = str(v)


title = doc.add_heading("Пояснение для научного руководителя: LLM-триаж алертов SIEM", level=0)
title.alignment = WD_ALIGN_PARAGRAPH.CENTER
p("Как всё устроено — простыми словами. Разработанный прототип: связка классического ML и "
  "языковых моделей (LLM) расставляет приоритеты алертам SIEM и формирует объяснения на русском языке.",
  bold=True)

