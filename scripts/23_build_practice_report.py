def table(doc, header, rows, caption=None):
    if caption:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(8)
        set_run(p.add_run(caption), size=13, bold=True)
        p.paragraph_format.keep_with_next = True
    n = len(header)
    size = 12 if n <= 4 else (10 if n <= 7 else 9)
    t = doc.add_table(rows=1, cols=n)
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    hdr = t.rows[0].cells
    for j, h in enumerate(header):
        hdr[j].text = ""
        if n > 7:  # узкие столбцы: переносим длинные заголовки по слогам, а не по произвольной букве
            h = {"Найдено": "Най-\nдено", "Ложных": "Лож-\nных", "Отмечено атакой": "Отме-\nчено\nата-\nкой", "Обучение, с": "Обуче-\nние, с"}.get(h, h)
        set_run(hdr[j].paragraphs[0].add_run(h), size=size, bold=True)
        hdr[j].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    for row in rows:
        cells = t.add_row().cells
        for j, val in enumerate(row):
            cells[j].text = ""
            set_run(cells[j].paragraphs[0].add_run(str(val)), size=size)
            cells[j].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    # таблица не разрывается между страницами (все таблицы отчёта короче страницы), шапка повторяется
    from docx.oxml.ns import qn
    from docx.oxml import OxmlElement
    trPr = t.rows[0]._tr.get_or_add_trPr()
    hdr_el = OxmlElement("w:tblHeader"); hdr_el.set(qn("w:val"), "true"); trPr.append(hdr_el)
    for row_ in t.rows[:-1]:
        for c_ in row_.cells:
            for p_ in c_.paragraphs:
                p_.paragraph_format.keep_with_next = True
    if n > 4:
        total = 16.5
        first = 3.6 if n > 6 else 3.2
        rest = (total - first) / (n - 1)
        for j, col in enumerate(t.columns):
            col.width = Cm(first if j == 0 else rest)
        for r in t.rows:
            for j, c in enumerate(r.cells):
                c.width = Cm(first if j == 0 else rest)
            for c in r.cells:
                for para_ in c.paragraphs:
                    para_.paragraph_format.line_spacing = 1.0
                    para_.paragraph_format.space_after = Pt(0)
    return t


def bullet(doc, text):
    p = para(doc, text, first_indent=True, left=1.0)
    p.paragraph_format.left_indent = Cm(1.0)


