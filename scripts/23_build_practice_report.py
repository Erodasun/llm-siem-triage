def set_run(run, size=14, bold=False, italic=False):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn('w:rFonts'))
    if rfonts is None:
        rfonts = OxmlElement('w:rFonts')
        rpr.append(rfonts)
    for a in ('w:ascii', 'w:hAnsi', 'w:cs', 'w:eastAsia'):
        rfonts.set(qn(a), FONT)


def para(doc, text="", align=WD_ALIGN_PARAGRAPH.JUSTIFY, size=14, bold=False,
         first_indent=True, space_after=6, line=1.5, left=None):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    if first_indent and text:
        pf.first_line_indent = Cm(1.25)
    if left is not None:
        pf.left_indent = Cm(left)
    pf.line_spacing = line
    pf.space_after = Pt(space_after)
    if text:
        set_run(p.add_run(text), size=size, bold=bold)
    return p


def heading(doc, text, level=1):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if level == 1 else WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(6)
    p.style = doc.styles["Heading 1"] if level == 1 else doc.styles["Heading 2"]
    for r in p.runs:
        set_run(r, size=16 if level == 1 else 14, bold=True)
    set_run(p.add_run(text), size=16 if level == 1 else 14, bold=True)
    return p


